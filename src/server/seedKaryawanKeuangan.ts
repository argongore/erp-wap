// Helper to construct CatatanUpahHarian
function makeUpahRow(
  id: string,
  tanggalKerja: string,
  hariTanggal: string,
  idKaryawan: string,
  nikKaryawan: string,
  namaKaryawan: string,
  jabatan: string,
  divisi: any,
  divisiKode: string,
  item: string,
  kuantiti: number,
  harga: number,
  ket: 'BON' | 'LUNAS',
  catatan?: string
): CatatanUpahHarian {
  const jumlah = kuantiti * harga;
  return {
    id,
    tanggalKerja,
    hariTanggal,
    idKaryawan,
    nikKaryawan,
    namaKaryawan,
    jabatan,
    divisi,
    divisiKode,
    kategori: 'KELUAR',
    rekening: 'HUTANG',
    jenisDana: 'GAJI',
    item,
    kuantiti,
    harga,
    jumlah,
    ket,
    catatan: catatan || '',
    upahHarian: harga,
    uangMakanLembur: 0,
    totalUpahHarian: jumlah,
    keterangan: item + (catatan ? ` (${catatan})` : ''),
    status: ket === 'LUNAS' ? 'SUDAH_DIBAYAR' : 'TERCATAT',
    createdAt: '2026-09-01T17:00:00.000Z',
  };
}

